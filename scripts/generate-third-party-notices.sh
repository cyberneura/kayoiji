#!/usr/bin/env bash
# 配布物に入る第三者のライブラリとデータのライセンスを THIRD-PARTY-NOTICES.txt に書く。`pnpm notices` から呼ぶ。
# 依存を足したり上げたりしたら、実行し直してコミットする (src-tauri のテストが、直接の依存が載っているかを確かめる)。
#
# 節は 3 つ:
# - JavaScript: 候補ウインドウと設定画面の WebView に入るパッケージ。`dependencies` の @tailwindcss/vite は
#   ビルドの道具で配布物に入らず、逆に devDependencies の svelte などは入るので、パッケージ名を
#   BUNDLED_PACKAGES に書く。この一覧は `vite build --sourcemap true` の client の sourcemap に現れる
#   node_modules のパッケージと、CSS に入る tailwindcss から決めた。WebView に入る依存を足したら、ここにも足す
# - Rust: cargo-about (`cargo install cargo-about --locked --features cli`)。設定は src-tauri/about.toml、
#   書式は src-tauri/about.hbs
# - 辞書と絵文字のデータ: THIRD-PARTY-NOTICES.md の内容と、Mozc の辞書の README (IPAdic と沖縄辞書の
#   ライセンス)、英単語の頻度表の LICENSE。後の 2 つは `pnpm data` で取得したファイルから読む
set -euo pipefail

cd "$(dirname "$0")/.."

OUT="THIRD-PARTY-NOTICES.txt"

if ! cargo about --version >/dev/null 2>&1; then
  echo "Error: cargo-about is not installed. Run: cargo install cargo-about --locked --features cli" >&2
  exit 1
fi
if [ ! -d node_modules ]; then
  echo "Error: node_modules is missing. Run: pnpm install" >&2
  exit 1
fi
for file in data/raw/mozc/README.txt data/raw/english/LICENSE; do
  if [ ! -s "$file" ]; then
    echo "Error: $file is missing. Run: pnpm data" >&2
    exit 1
  fi
done

# 同じディレクトリに作る。別のファイルシステムの /tmp からの mv はコピーになり、途中で止まると壊れた出力が残る。
TMP=$(mktemp "${OUT}.XXXXXX")
ALL_JSON=$(mktemp "${OUT}.all.XXXXXX")
trap 'rm -f "$TMP" "$ALL_JSON"' EXIT

pnpm licenses list --json > "$ALL_JSON"

{
  cat <<'HEADER'
THIRD-PARTY NOTICES

Kayoiji bundles the open source libraries and data listed below. Each entry gives
the license, the packages it applies to, and the license text as shipped by the
package. Generated by scripts/generate-third-party-notices.sh; do not edit by hand.

################################################################################
# JavaScript packages (bundled into the web view)
################################################################################

HEADER

  ALL_JSON="$ALL_JSON" node - <<'NODE'
const fs = require("fs");
const path = require("path");

const BUNDLED_PACKAGES = ["@sveltejs/kit", "@tauri-apps/api", "esm-env", "svelte", "tailwindcss"];

const all = Object.values(JSON.parse(fs.readFileSync(process.env.ALL_JSON, "utf8"))).flat();
for (const name of BUNDLED_PACKAGES) {
  const entry = all.find((e) => e.name === name);
  if (!entry) throw new Error(`${name} is not installed`);
  if (entry.versions.length !== 1) {
    // 複数の版がある時は、どれが配布物に入ったかをここでは決められない。
    throw new Error(`${name} has several versions: ${entry.versions.join(", ")}`);
  }
  const dir = entry.paths[0];
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const repo = typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url;
  const files = fs
    .readdirSync(dir)
    .filter((f) => /^(LICEN[CS]E|COPYING|NOTICE)/i.test(f) && !/\.spdx$/i.test(f))
    .sort();
  if (files.length === 0) throw new Error(`${name} ships no license file; add its license text by hand`);
  console.log("=".repeat(80));
  console.log(`License: ${manifest.license}`);
  console.log("");
  console.log("Used by:");
  console.log(`  ${name} ${entry.versions[0]}${repo ? ` (${repo})` : ""}`);
  console.log("");
  for (const f of files) {
    if (files.length > 1) console.log(`--- ${f} ---`);
    console.log(fs.readFileSync(path.join(dir, f), "utf8").replace(/\s+$/, ""));
    console.log("");
  }
}
NODE

  cat <<'HEADER'
################################################################################
# Rust crates (compiled into the binary)
################################################################################

HEADER

  # --fail: ライセンスが分からないクレートがあれば、警告で載せずに済ませるのではなく失敗する。
  cargo about generate --manifest-path src-tauri/Cargo.toml --locked --fail src-tauri/about.hbs

  cat <<'HEADER'
################################################################################
# Dictionaries and emoji data (built from the sources below and shipped as data)
################################################################################

HEADER
  cat THIRD-PARTY-NOTICES.md
  echo ""
  echo "================================================================================"
  echo "Mozc dictionary_oss/README.txt (licenses of IPAdic and the Okinawa dictionary)"
  echo ""
  cat data/raw/mozc/README.txt
  echo ""
  echo "================================================================================"
  echo "wikipedia-word-frequency LICENSE"
  echo ""
  cat data/raw/english/LICENSE
} > "$TMP"

mv "$TMP" "$OUT"
echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
